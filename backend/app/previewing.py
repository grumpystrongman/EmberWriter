def _chapter_html(content: str) -> str:
    return markdown_lib.markdown(content, extensions=["extra", "sane_lists"])


def preview_payload(
    slug: str,
    *,
    title: str,
    author: str = "",
    trim_width: float = 6.0,
    trim_height: float = 9.0,
) -> dict:
    documents = compiled_documents(slug)
    return {
        "title": title,
        "author": author,
        "trim_width": trim_width,
        "trim_height": trim_height,
        "documents": [
            {
                "title": item["title"],
                "path": item["path"],
                "word_count": item["word_count"],
                "html": _chapter_html(item["content"]),
            }
            for item in documents
        ],
        "words": sum(int(item.get("word_count") or 0) for item in documents),
    }


