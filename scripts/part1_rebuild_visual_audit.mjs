// End-to-end browser acceptance for the Part 1 rebuild. Synthetic data only.
import fs from 'node:fs'
import path from 'node:path'
const root=path.resolve(import.meta.dirname,'..')
const output=path.join(root,'docs','screenshots','part1-rebuild')
fs.mkdirSync(output,{recursive:true})
const series=await(await fetch('http://127.0.0.1:8000/api/series')).json()
if(series.length!==1||series[0].title!=='The Astral Lanterns'||series[0].volume_count!==4)throw Error('Refusing non-synthetic fixture')
const sid=series[0].id
const targets=await(await fetch('http://127.0.0.1:9227/json')).json()
const page=targets.find(x=>x.type==='page'&&x.url.startsWith('http://127.0.0.1:5173'))
if(!page)throw Error('Synthetic browser not available')
const ws=new WebSocket(page.webSocketDebuggerUrl)
await new Promise((resolve,reject)=>{ws.onopen=resolve;ws.onerror=reject})
let id=0;const pending=new Map()
ws.onmessage=e=>{const m=JSON.parse(e.data);const p=pending.get(m.id);if(!p)return;pending.delete(m.id);m.error?p.reject(Error(JSON.stringify(m.error))):p.resolve(m.result)}
const send=(method,params={})=>new Promise((resolve,reject)=>{const k=++id;pending.set(k,{resolve,reject});ws.send(JSON.stringify({id:k,method,params}))})
async function evaluate(expression){const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw Error(JSON.stringify(r.exceptionDetails));return r.result?.value}
const wait=ms=>new Promise(r=>setTimeout(r,ms))
async function until(expression,message){for(let i=0;i<24;i++){if(await evaluate(expression))return;await wait(500)}throw Error(message)}
async function screenshot(name,w=1440,h=900,selector='.story-observatory'){
 await send('Emulation.setDeviceMetricsOverride',{width:w,height:h,deviceScaleFactor:1,mobile:w<600})
 await wait(500)
 await evaluate('document.querySelector('+JSON.stringify(selector)+')?.scrollIntoView({block:"start"});window.scrollBy(0,-8);true')
 await wait(250)
 const image=await send('Page.captureScreenshot',{format:'png',captureBeyondViewport:false})
 fs.writeFileSync(path.join(output,name+'.png'),Buffer.from(image.data,'base64'))
 const status=await evaluate('({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,active:[...document.querySelectorAll(".observatory-lenses button")].find(x=>x.getAttribute("aria-pressed")==="true")?.innerText,errors:[...document.querySelectorAll("[role=alert]")].map(x=>x.innerText.slice(0,150))})')
 if(status.scrollWidth>w+3)throw Error('Viewport horizontal overflow '+JSON.stringify(status))
 console.log('SHOT',name,JSON.stringify(status))
}
const tab=async label=>{await evaluate('([...document.querySelectorAll(".observatory-lenses button")].find(x=>x.innerText.includes('+JSON.stringify(label)+'))?.click(),true)');await wait(850)}
try{
 await send('Page.enable')
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false})
 await evaluate('localStorage.setItem("emberwriter.workspace","series");location.reload();true')
 await until('!!document.querySelector(".story-observatory")','Observatory missing')
 await until('!!document.querySelector(".observatory-graph-node")','Nodes missing')
 await screenshot('01-world-1440')
 await tab('Discover')
 await until('document.querySelectorAll(".discovery-lead").length>10','Discovery found no source leads')
 const before=Number(await evaluate('document.querySelector(".discovery-score strong")?.innerText'))
 if(before<10)throw Error('Expected multiple synthetic unreviewed leads, got '+before)
 const previouslyPending=(await(await fetch('http://127.0.0.1:8000/api/series/'+sid+'/assertions?status=proposed')).json()).length
 await screenshot('02-discovery-1440')
 await screenshot('03-discovery-900',900,800)
 await screenshot('04-discovery-390',390,844)
 await send('Emulation.setDeviceMetricsOverride',{width:1440,height:900,deviceScaleFactor:1,mobile:false})
 await wait(350)
 await evaluate('document.querySelector(".discovery-stage-button")?.click();true')
 await until('document.querySelector(".discovery-notice")?.innerText.includes("not canon")','Stage confirmation absent')
 const changed=await(await fetch('http://127.0.0.1:8000/api/series/'+sid+'/assertions?status=proposed')).json()
 if(changed.length!==previouslyPending+1)throw Error('Staged proposal not in pending canon: '+changed.length)
 const after=await(await fetch('http://127.0.0.1:8000/api/series/'+sid+'/discover')).json()
 if(after.total>=before)throw Error('Discovery did not de-duplicate staged evidence')
 await screenshot('05-discovery-staged-1440')
 await tab('Universe')
 await evaluate('(()=>{[...document.querySelectorAll(".observatory-book-track button")].find(x=>x.innerText.includes("BOOK 4"))?.click();return true})()')
 await until('document.querySelector(".observatory-scene-scrubber input")!==null','Scene time scrubber missing')
 await screenshot('06-book-scene-time-1440')
 const timeBefore=await evaluate('document.querySelector(".observatory-hero-stats")?.innerText')
 await evaluate('(()=>{let x=document.querySelector(".observatory-scene-scrubber input");const proto=HTMLInputElement.prototype;Object.getOwnPropertyDescriptor(proto,"value").set.call(x,"0");x.dispatchEvent(new Event("input",{bubbles:true}));x.dispatchEvent(new Event("change",{bubbles:true}));return true})()')
 await wait(1000)
 const timeAfter=await evaluate('document.querySelector(".observatory-hero-stats")?.innerText')
 console.log('TIME-SCRUB BEFORE/AFTER',JSON.stringify({timeBefore,timeAfter}))
 await evaluate('document.querySelector(".observatory-utility-bar button")?.click();true')
 await until('document.querySelector(".story-observatory.is-immersive")!==null','Immersive mode did not open')
 await screenshot('07-immersive-1440')
 await send('Input.dispatchKeyEvent',{type:'keyDown',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
 await send('Input.dispatchKeyEvent',{type:'keyUp',key:'Escape',code:'Escape',windowsVirtualKeyCode:27})
 await until('!document.querySelector(".story-observatory.is-immersive")','Escape did not exit immersive mode')
 await screenshot('08-returned-1440')
 await tab('Character minds')
 await screenshot('09-character-minds-1440')
 await tab('Plot threads')
 await screenshot('10-plot-threads-1440')
 await tab('Model Lab')
 await until('document.querySelector(".model-lab-actions select")?.options.length>1','Local model discovery did not populate')
 await screenshot('11-local-model-lab-1440')
 console.log('PASS: synthetic browser source discovery → stage → book-time → immersive → character/threads/model')
}catch(e){console.error('FAILED',e.stack||e);process.exitCode=1}
finally{ws.close()}
