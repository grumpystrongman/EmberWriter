def build_preview_site(slug: str, *, title: str, author: str = "") -> dict:
    payload = preview_payload(slug, title=title, author=author)
    root = project_root(slug)
    export_root = root / "exports" / f"preview-site-{uuid4().hex[:10]}"
    export_root.mkdir(parents=True, exist_ok=True)
    index_path = export_root / "index.html"
    index_path.write_text(_site_html(payload), encoding="utf-8")
    readme = export_root / "README.txt"
    readme.write_text(
        "EmberWriter private preview package.\n\n"
        "Open index.html locally to preview. For remote sharing, upload this folder to a host protected "
        "by authentication or another access-control layer. This static package is not itself a security boundary.\n",
        encoding="utf-8",
    )
    zip_path = export_root.with_suffix(".zip")
    with zipfile.ZipFile(zip_path, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        archive.write(index_path, arcname="index.html")
        archive.write(readme, arcname="README.txt")
    return {
        "filename": zip_path.name,
        "relative_path": str(zip_path.relative_to(root)).replace("\\", "/"),
        "bytes": zip_path.stat().st_size,
        "documents": len(payload["documents"]),
        "words": payload["words"],
    }
